#!/usr/bin/env bash
# install_hooks.sh — Install PII scanner as a git pre-commit hook.
#
# Run from repo root:
#   bash scripts/install_hooks.sh
#
# Idempotent: safe to re-run. If a pre-commit hook already exists, it is
# backed up to .git/hooks/pre-commit.bak before being replaced.

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOK_PATH="$REPO_ROOT/.git/hooks/pre-commit"

if [[ -f "$HOOK_PATH" && ! -L "$HOOK_PATH" ]]; then
  if ! grep -q "pii_scan.py" "$HOOK_PATH"; then
    cp "$HOOK_PATH" "$HOOK_PATH.bak"
    echo "install_hooks: backed up existing pre-commit to $HOOK_PATH.bak"
  fi
fi

cat > "$HOOK_PATH" <<'HOOK'
#!/usr/bin/env bash
# Auto-generated by scripts/install_hooks.sh
# Runs the PII scanner against staged files. Exits non-zero on any hit,
# blocking the commit.
set -euo pipefail
REPO_ROOT="$(git rev-parse --show-toplevel)"
exec python "$REPO_ROOT/scripts/pii_scan.py"
HOOK

chmod +x "$HOOK_PATH"
echo "install_hooks: pre-commit hook installed at $HOOK_PATH"
echo "install_hooks: test by staging a file containing a known last-4 and running 'git commit'."
